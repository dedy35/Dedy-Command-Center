import type { PromptTemplate } from "@/config/prompts";

type MockAiInput = {
  prompt: PromptTemplate;
  inputText: string;
};

function cleanLines(text: string) {
  return text
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter(Boolean);
}

function summarizeForDraft(text: string, max = 240) {
  return text.length <= max ? text : `${text.slice(0, max)}...`;
}

export async function runMockLocalAi({ prompt, inputText }: MockAiInput) {
  const lines = cleanLines(inputText);
  const firstLine = lines[0] ?? "(no input text)";

  if (prompt.key === "ticket_analysis_ja_v1") {
    return [
      "Issue:",
      `- ${firstLine}`,
      "",
      "Confirmed facts:",
      "- Input text was provided by user and saved as source.",
      "- Current draft is generated by mock local AI provider.",
      "",
      "Assumptions:",
      "- Missing details are treated as assumptions and need verification.",
      "",
      "Risks:",
      "- Overclaiming without evidence.",
      "- Missing edge-case validation before external update.",
      "",
      "Unclear points:",
      "- Pending scope and acceptance details.",
      "",
      "Next actions:",
      "- Confirm unclear points with senior/owner.",
      "- Update ticket with verified facts only.",
    ].join("\n");
  }

  if (prompt.key === "redmine_comment_draft_v1") {
    return [
      "【作業報告（下書き）】",
      `対象: ${firstLine}`,
      "現時点で確認できた事実のみ記載しています。",
      "未確認事項は仮説として整理し、追加確認後に更新します。",
      "引き続き調査・検証を進めます。",
    ].join("\n");
  }

  if (prompt.key === "teams_notification_v1") {
    return [
      "【短縮版】",
      `本件（${firstLine}）について、現状を整理しました。詳細はチケットに反映します。`,
      "",
      "【詳細版】",
      "- 事実ベースで現状を整理済み",
      "- 未確定項目は確認中",
      "- 次アクションをチケットへ追記予定",
    ].join("\n");
  }

  if (prompt.key === "daily_log_rewrite_v1") {
    return [
      "Professional Daily Log Draft:",
      `- ${summarizeForDraft(inputText, 300)}`,
      "- Rewritten for clarity and workplace readiness.",
    ].join("\n");
  }

  return [
    "STAR/CV Draft:",
    `Situation/Task: ${firstLine}`,
    "Action: Performed analysis and execution based on available facts.",
    "Result: Impact metric not confirmed yet.",
    "Impact questions: What measurable latency/quality/cost change was observed?",
  ].join("\n");
}
